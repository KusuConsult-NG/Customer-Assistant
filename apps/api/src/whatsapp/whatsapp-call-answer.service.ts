/**
 * Answering a WhatsApp call, rather than only recording that it happened.
 *
 * ── What Meta requires, and why this is not a config change ─────────────────
 *
 * A `calls` webhook with `event: "connect"` carries an SDP **offer**. To answer
 * it the business must POST an SDP **answer** back to
 * `/{phone-number-id}/calls` and then terminate WebRTC media itself: ICE, a
 * DTLS handshake, SRTP, and Opus at 48 kHz. There is no `<Connect><Stream/>`
 * equivalent — Meta will not bridge the audio to a WebSocket for us the way
 * Twilio's Media Streams do. That is the whole reason this file exists and the
 * reason it is the largest thing in the WhatsApp module.
 *
 * ── OFF BY DEFAULT, and it refuses to enable itself ─────────────────────────
 *
 * The worst outcome here is a line that ANSWERS and then delivers silence: the
 * citizen's call is consumed, the carrier reports it completed, and the
 * existing fallback (record the call, write the citizen a message) never runs
 * because from Meta's side the call was handled. That is the "looks
 * provisioned" failure this repo keeps legislating against, so enabling takes
 * two independent things and the service says which one is missing:
 *
 *   1. `WHATSAPP_CALL_ANSWER=1` — the deliberate opt-in.
 *   2. A TURN relay (`TURN_URL` + `TURN_USERNAME` + `TURN_CREDENTIAL`).
 *
 * The second is not optional and not a nicety. WebRTC media is UDP, and the
 * API is deployed on Render, which exposes one HTTP port and no inbound UDP —
 * so Meta cannot reach a host candidate and media has to relay through TURN,
 * which we reach outbound. Without it ICE produces a `host` candidate that is
 * unreachable from the internet, the DTLS handshake never completes, and the
 * caller gets an answered call with no audio. Enabling the flag alone would
 * therefore be strictly worse than leaving this off, which is why
 * `readiness()` treats missing TURN as BLOCKED rather than degraded.
 *
 * ── NOT YET PROVEN BY A REAL CALL ──────────────────────────────────────────
 *
 * No WhatsApp call has been answered by this code. The signalling below is
 * unit-tested against Meta's documented payload shape and the SDP answer is
 * generated by a real WebRTC stack, but a sandbox cannot place a WhatsApp call,
 * so the end-to-end path is UNVERIFIED. Treat the first real call as the test.
 * `TwilioMediaStreamHandler` carries the same warning and its protocol is far
 * simpler, so do not read "the code exists" as "voice works".
 */
import { Injectable } from '@nestjs/common';
import { AceLogger } from '../config/logger';
import { WhatsAppCallMediaService } from './whatsapp-call-media.service';

const log = new AceLogger('WhatsAppCallAnswer');

/** Meta's Graph version, matching the rest of the WhatsApp paths. */
const GRAPH_VERSION = 'v21.0';

/** What `connect` carried, reduced to the parts we act on. */
export interface CallOffer {
  callId: string;
  phoneNumberId: string;
  /** The SDP offer Meta sent. */
  sdp: string;
  /** Whose call this is, and who is calling — the media bridge needs both to
   * run the conversation against the right tenant and contact. */
  organizationId: string;
  citizenNumber: string;
}

/** One relay, in the shape werift's `iceServers` takes. */
export interface IceServer {
  urls: string;
  username: string;
  credential: string;
}

export type AnswerOutcome =
  | { answered: true; detail: string }
  | { answered: false; reason: string; blocked: boolean };

/** Why answering is or is not available, in the words an operator needs. */
export interface CallAnswerReadiness {
  enabled: boolean;
  blocked: string[];
  detail: string;
}

@Injectable()
export class WhatsAppCallAnswerService {
  constructor(private readonly media?: WhatsAppCallMediaService) {}

  /**
   * Is answering switched on AND actually possible?
   *
   * Reported together on purpose. "Configured" is not an answer in this
   * codebase: the flag says somebody intended this, TURN says the media can
   * reach us, and only both of them mean a caller will hear anything.
   */
  readiness(): CallAnswerReadiness {
    const optedIn = process.env.WHATSAPP_CALL_ANSWER === '1';
    const blocked: string[] = [];

    if (!optedIn) {
      blocked.push(
        'WHATSAPP_CALL_ANSWER is not 1, so inbound WhatsApp calls are recorded and replied to by message rather than answered.'
      );
    }

    const mode = this.relayMode();
    if (mode === 'none') {
      blocked.push(
        'No TURN relay is configured. Set TURN_URL/TURN_USERNAME/TURN_CREDENTIAL for your own relay (coturn), or ' +
          'TURN_PROVIDER=twilio to mint ephemeral credentials from the deployment\'s Twilio account. WebRTC media ' +
          'is UDP and this deployment has no inbound UDP, so without a relay an answered call carries no audio — ' +
          'which is worse than not answering, because the caller is consumed and the message fallback never runs.'
      );
    }
    if (mode === 'twilio-incomplete') {
      blocked.push(
        'TURN_PROVIDER is twilio but TWILIO_ACCOUNT_SID and TWILIO_AUTH_TOKEN are not both set, so no relay ' +
          'credential can be minted.'
      );
    }

    const enabled = optedIn && (mode === 'static' || mode === 'twilio');
    return {
      enabled,
      blocked,
      detail: enabled
        ? `Inbound WhatsApp calls will be answered, relaying through ${
            mode === 'twilio' ? "Twilio's Network Traversal Service" : 'the configured TURN server'
          }. No real call has proven this path yet — treat the first one as the test.`
        : blocked.join(' '),
    };
  }

  /** Which relay this deployment is set up for, and whether it is complete. */
  private relayMode(): 'static' | 'twilio' | 'twilio-incomplete' | 'none' {
    if (process.env.TURN_PROVIDER?.trim().toLowerCase() === 'twilio') {
      return process.env.TWILIO_ACCOUNT_SID?.trim() && process.env.TWILIO_AUTH_TOKEN?.trim()
        ? 'twilio'
        : 'twilio-incomplete';
    }
    const urls = process.env.TURN_URL?.trim();
    const username = process.env.TURN_USERNAME?.trim();
    const credential = process.env.TURN_CREDENTIAL?.trim();
    return urls && username && credential ? 'static' : 'none';
  }

  /**
   * Cached ephemeral credentials, so a relay is not minted per call.
   *
   * Twilio's tokens last up to 24 hours. Fetching one per call adds a round
   * trip to the answer path, and Meta drops an unanswered call quickly — a
   * slow answer is the same as none. Refreshed at 90% of the stated lifetime
   * so a call never starts against a credential that expires mid-negotiation.
   */
  private cachedIce: { servers: IceServer[]; expiresAt: number } | null = null;

  /**
   * The relay(s) to offer ICE, or null when none is configured.
   *
   * Returns a LIST, not one server. Twilio hands back TURN over UDP 3478 and
   * over TCP 443, and the second is what gets through a network that blocks
   * UDP egress — exactly the restrictive conditions a citizen's phone may be
   * on. Offering only the first would decline calls that would have connected.
   */
  private async iceServers(): Promise<IceServer[] | null> {
    const mode = this.relayMode();

    if (mode === 'static') {
      return [
        {
          urls: process.env.TURN_URL!.trim(),
          username: process.env.TURN_USERNAME!.trim(),
          credential: process.env.TURN_CREDENTIAL!.trim(),
        },
      ];
    }

    if (mode !== 'twilio') return null;

    if (this.cachedIce && this.cachedIce.expiresAt > Date.now()) return this.cachedIce.servers;

    const sid = process.env.TWILIO_ACCOUNT_SID!.trim();
    const token = process.env.TWILIO_AUTH_TOKEN!.trim();
    try {
      const res = await fetch(`https://api.twilio.com/2010-04-01/Accounts/${encodeURIComponent(sid)}/Tokens.json`, {
        method: 'POST',
        headers: {
          Authorization: `Basic ${Buffer.from(`${sid}:${token}`).toString('base64')}`,
          'Content-Type': 'application/x-www-form-urlencoded',
        },
        signal: AbortSignal.timeout(5000),
      });
      if (!res.ok) {
        const body = await res.text().catch(() => '');
        log.error(
          'turn_credential_refused',
          new Error(`Twilio refused a Network Traversal token (HTTP ${res.status}): ${body.slice(0, 200)}`)
        );
        return null;
      }
      const payload: any = await res.json();
      // Entries with no credential are bare STUN. STUN discovers a public
      // address; it does not relay, and this deployment needs a relay because
      // it has no inbound UDP. Keeping them would let ICE "succeed" with a
      // srflx candidate that Meta still cannot reach.
      const servers: IceServer[] = (Array.isArray(payload?.ice_servers) ? payload.ice_servers : [])
        .filter((s: any) => s?.urls && s?.username && s?.credential)
        .map((s: any) => ({ urls: String(s.urls), username: String(s.username), credential: String(s.credential) }));

      if (servers.length === 0) {
        log.error(
          'turn_credential_empty',
          new Error('Twilio returned a token carrying no TURN server, only STUN, so media could not be relayed.')
        );
        return null;
      }

      const ttl = Number(payload?.ttl);
      const lifetime = Number.isFinite(ttl) && ttl > 0 ? ttl : 3600;
      this.cachedIce = { servers, expiresAt: Date.now() + lifetime * 1000 * 0.9 };
      return servers;
    } catch (err: any) {
      log.error('turn_credential_unreachable', err instanceof Error ? err : new Error(String(err)));
      return null;
    }
  }

  /**
   * Answer a call: negotiate an SDP answer and hand it to Meta.
   *
   * NEVER THROWS. The caller has already recorded the call and has a working
   * message fallback, and an exception here would lose both. Every refusal
   * names what went wrong so `processCallEvent` can write it into the thread
   * instead of reporting an answer it did not achieve.
   *
   * Returns `answered: false` with `blocked: true` when answering was never
   * available, so the caller can tell "switched off" from "tried and failed".
   */
  async answer(offer: CallOffer, accessToken: string, correlationId: string): Promise<AnswerOutcome> {
    const readiness = this.readiness();
    if (!readiness.enabled) {
      return { answered: false, reason: readiness.detail, blocked: true };
    }

    if (!offer.sdp?.trim()) {
      // Meta sends the offer on `connect`; without one there is nothing to
      // answer, and inventing an answer would accept a call we cannot carry.
      return {
        answered: false,
        reason: 'The connect event carried no SDP offer, so there was nothing to negotiate against.',
        blocked: false,
      };
    }

    try {
      const ice = await this.iceServers();
      if (!ice) {
        // readiness() said a relay was configured, and minting one still
        // failed — a credential problem, not a configuration one, so it is
        // reported as an attempt that failed rather than as switched off.
        return {
          answered: false,
          reason:
            'The TURN relay credentials could not be obtained, so the call was not answered and the citizen ' +
            'still gets a message. The cause is in the log line above this one.',
          blocked: false,
        };
      }
      const negotiated = await this.negotiate(offer.sdp, ice);
      if ('error' in negotiated) {
        return { answered: false, reason: negotiated.error, blocked: false };
      }
      // From here the connection is LIVE and this method owns it: every exit
      // below either hands it to the media bridge or closes it. A returned
      // `answered: false` with a peer connection still open would leak a
      // WebRTC session and its sockets per declined call.
      const live = (negotiated as any).pc;

      // A RELAY candidate, not merely any candidate.
      //
      // This is the check that refuses the failure the whole flag exists to
      // avoid. A `host` candidate is always gathered and is always useless:
      // it is this pod's private address, which Meta cannot reach. Accepting
      // on the strength of one would answer the call, carry no audio, and
      // suppress the message fallback — the citizen consumed for nothing.
      // No relay candidate means the TURN allocation failed, so we decline and
      // let the fallback run.
      // The candidate line is `candidate:<foundation> <component> <transport>
      // <priority> <address> <port> typ <type> …`, so `typ relay` sits seven
      // fields in. An earlier version of this matched `\S+ typ relay` and so
      // matched nothing at all — it would have declined every call even with a
      // perfectly healthy relay, and the decline reads identically to a broken
      // TURN server. The test that pins a real relay candidate is what caught it.
      if (!/a=candidate:[^\r\n]*\btyp relay\b/.test(negotiated.sdp)) {
        await this.close(live);
        return {
          answered: false,
          reason:
            'The TURN relay did not allocate, so the answer carried no route Meta could send media to — only a ' +
            'local host candidate, which is unreachable from the internet. Check TURN_URL, TURN_USERNAME and ' +
            'TURN_CREDENTIAL against the relay. Declining rather than answering, so the citizen still gets a reply.',
          blocked: false,
        };
      }

      const sent = await this.sendAnswerToMeta(offer, negotiated.sdp, accessToken);
      if (!sent.ok) {
        await this.close(live);
        return { answered: false, reason: sent.error, blocked: false };
      }

      // Audio only exists if this runs. Without it Meta has been told the call
      // is accepted and the caller hears nothing at all — so a missing media
      // service is reported as a failure, not shrugged off.
      if (!this.media || !live) {
        await this.close(live);
        return {
          answered: false,
          reason:
            'The call was negotiated but no media bridge was available to carry audio, so it was not accepted ' +
            'as answered. This is a wiring fault, not a configuration one.',
          blocked: false,
        };
      }
      await this.media.attach({
        pc: live,
        organizationId: offer.organizationId,
        callId: offer.callId,
        citizenNumber: offer.citizenNumber,
        correlationId,
      });

      log.info('whatsapp_call_answered', {
        correlationId,
        callId: offer.callId,
        note: 'Meta accepted the SDP answer. Audio depends on the media bridge, which no real call has proven.',
      });

      return {
        answered: true,
        detail: 'Meta accepted the answer and the call was connected.',
      };
    } catch (err: any) {
      log.error('whatsapp_call_answer_failed', err, { correlationId, callId: offer.callId });
      return {
        answered: false,
        reason: `Negotiating the call failed (${String(err?.message ?? 'unknown error').slice(0, 200)}).`,
        blocked: false,
      };
    }
  }

  /**
   * Turn Meta's offer into an SDP answer with a real WebRTC stack.
   *
   * Separated so the tests can drive the paths AFTER negotiation — Meta's
   * refusals, the relay check — without a TURN server. A sandbox cannot
   * allocate a relay, so without this seam those branches would be unreachable
   * in tests and the only covered outcome would be "no relay".
   */
  protected async negotiate(
    offerSdp: string,
    iceServers: IceServer[]
  ): Promise<{ sdp: string; pc?: any } | { error: string }> {
    let pc: any;
    try {
      // Required lazily so the WebRTC stack is not constructed in every
      // process that imports the WhatsApp module — including the test suites
      // that never answer a call.
      // eslint-disable-next-line @typescript-eslint/no-var-requires
      const { RTCPeerConnection } = require('werift');

      pc = new RTCPeerConnection({
        // Codecs are deliberately left empty: the answer must offer back what
        // Meta asked for, and taking them from the remote description is what
        // keeps this from hard-coding a payload type Meta may change.
        codecs: { audio: [] },
        iceServers,
      });
      pc.addTransceiver('audio', { direction: 'sendrecv' });

      await pc.setRemoteDescription({ type: 'offer', sdp: offerSdp });
      await pc.setLocalDescription(await pc.createAnswer());

      // Non-trickle: Meta takes one answer, so gathering has to settle before
      // it is sent or the answer carries no reachable candidate.
      await this.awaitGathering(pc);

      const sdp: string = pc.localDescription?.sdp ?? '';
      if (!sdp) {
        await this.close(pc);
        return { error: 'The WebRTC stack produced no answer to send.' };
      }
      // Deliberately NOT closed: the caller needs this connection to carry
      // audio, and closing it here is what made the first version of this
      // negotiate an answer nobody could speak over.
      return { sdp, pc };
    } catch (err: any) {
      await this.close(pc);
      return {
        error: `Could not build an SDP answer (${String(err?.message ?? 'unknown error').slice(0, 200)}).`,
      };
    }
  }

  /**
   * Wait for ICE gathering, bounded.
   *
   * Meta drops an unanswered call quickly, so this cannot wait indefinitely for
   * a relay that is not responding — a late answer is the same as none, and
   * holding the webhook open past Meta's timeout turns one failure into two.
   */
  private async awaitGathering(pc: any, timeoutMs = 4000): Promise<void> {
    const start = Date.now();
    while (pc.iceGatheringState !== 'complete' && Date.now() - start < timeoutMs) {
      await new Promise((r) => setTimeout(r, 100));
    }
  }

  /** POST the answer. Separated so the tests can drive Meta's refusals. */
  private async sendAnswerToMeta(
    offer: CallOffer,
    answerSdp: string,
    accessToken: string
  ): Promise<{ ok: true } | { ok: false; error: string }> {
    const url = `https://graph.facebook.com/${GRAPH_VERSION}/${encodeURIComponent(offer.phoneNumberId)}/calls`;
    let res: Response;
    try {
      res = await fetch(url, {
        method: 'POST',
        headers: { Authorization: `Bearer ${accessToken}`, 'Content-Type': 'application/json' },
        body: JSON.stringify({
          messaging_product: 'whatsapp',
          call_id: offer.callId,
          action: 'accept',
          session: { sdp_type: 'answer', sdp: answerSdp },
        }),
        signal: AbortSignal.timeout(5000),
      });
    } catch (err: any) {
      return { ok: false, error: `Could not reach Meta to accept the call (${err?.message ?? 'network error'}).` };
    }

    if (!res.ok) {
      const body = await res.text().catch(() => '');
      // Meta's own words. "Check your configuration" is what somebody reads
      // instead of the actual cause.
      return { ok: false, error: `Meta refused the answer (HTTP ${res.status}): ${body.slice(0, 300)}` };
    }
    return { ok: true };
  }

  /**
   * Hang up a call we answered.
   *
   * Best-effort and never throws: a failed terminate leaves Meta to time the
   * call out, which is untidy but not a lie told to anyone.
   */
  async terminate(offer: Pick<CallOffer, 'callId' | 'phoneNumberId'>, accessToken: string): Promise<boolean> {
    try {
      const res = await fetch(
        `https://graph.facebook.com/${GRAPH_VERSION}/${encodeURIComponent(offer.phoneNumberId)}/calls`,
        {
          method: 'POST',
          headers: { Authorization: `Bearer ${accessToken}`, 'Content-Type': 'application/json' },
          body: JSON.stringify({
            messaging_product: 'whatsapp',
            call_id: offer.callId,
            action: 'terminate',
          }),
          signal: AbortSignal.timeout(5000),
        }
      );
      return res.ok;
    } catch {
      return false;
    }
  }

  private async close(pc: any): Promise<void> {
    try {
      await pc?.close?.();
    } catch {
      /* closing a half-built connection is not a failure worth reporting */
    }
  }
}
